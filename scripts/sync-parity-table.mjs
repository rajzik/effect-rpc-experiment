// Regenerates the `ported` rows of docs/trpc-test-parity.md from every packages/*/test/PARITY.md.
// Manual `not-applicable` / `deferred` rows are kept unless a package ported that file.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { repoRoot } from './_run.mjs';

const norm = (p) =>
  p
    .trim()
    .replace(/^`|`$/g, '')
    .replace(/^packages\//, '');
const inventory = readFileSync(resolve(repoRoot, 'docs/trpc-test-inventory.txt'), 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map(norm);

// Collect ported mappings from package ledgers.
const ported = new Map(); // trpc file -> Set<local path>
for (const pkg of readdirSync(resolve(repoRoot, 'packages'))) {
  const file = resolve(repoRoot, 'packages', pkg, 'test', 'PARITY.md');
  if (!existsSync(file)) continue;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const cells = line
      .split('|')
      .slice(1, -1)
      .map((c) => c.trim());
    if (cells.length < 2 || /^-+$/.test(cells[0]) || /^trpc test/i.test(cells[0])) continue;
    const trpc = norm(cells[0]);
    if (!inventory.includes(trpc)) continue;
    const ticked = [...cells[1].matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    const locals =
      ticked.length > 0
        ? ticked
        : cells[1]
            .split(',')
            .map((c) => c.trim())
            .filter(Boolean);
    const set = ported.get(trpc) ?? new Set();
    for (const l of locals) set.add(`packages/${pkg}/test/${l}`);
    ported.set(trpc, set);
  }
}

// Hand-maintained rows live in docs/trpc-test-parity.manual.md.
const manual = new Map();
for (const line of readFileSync(resolve(repoRoot, 'docs/trpc-test-parity.manual.md'), 'utf8').split(
  '\n',
)) {
  const m =
    /^\|\s*`?([^|`]+?)`?\s*\|\s*(not-applicable|deferred|ported)\s*\|\s*(.*?)\s*\|\s*$/.exec(line);
  if (m) manual.set(norm(m[1]), { status: m[2], detail: m[3] });
}
const docPath = resolve(repoRoot, 'docs/trpc-test-parity.md');
const header = `# tRPC test parity

Every test file in \`docs/trpc-test-inventory.txt\` (trpc/trpc monorepo, excluding the legacy
\`packages/react-query\` hooks package) is classified below. This file is GENERATED by
\`node scripts/sync-parity-table.mjs\` from each package's \`test/PARITY.md\` (ported rows) and
\`docs/trpc-test-parity.manual.md\` (not-applicable / deferred rows). \`node scripts/verify-parity-table.mjs\`
enforces that every inventory file has a row and that every ported row points at existing tests.

Status meanings: \`ported\` — behaviour covered by the listed local tests; \`not-applicable\` — the tRPC
test exercises a mechanism this project does not have by design (reason given); \`deferred\` —
applicable but not yet ported (reason given).

`;
const rows = [];
let counts = { ported: 0, 'not-applicable': 0, deferred: 0, missing: 0 };
for (const file of inventory) {
  if (ported.has(file)) {
    rows.push(`| ${file} | ported | ${[...ported.get(file)].map((p) => `\`${p}\``).join(', ')} |`);
    counts.ported++;
  } else if (manual.has(file)) {
    const { status, detail } = manual.get(file);
    rows.push(`| ${file} | ${status} | ${detail} |`);
    counts[status]++;
  } else {
    rows.push(`| ${file} | deferred | UNCLASSIFIED — awaiting leaf delivery |`);
    // eslint-disable-next-line no-console
    console.warn(`unclassified: ${file}`);
    counts.missing++;
  }
}
writeFileSync(
  docPath,
  `${header}| tRPC test file | status | local tests / reason |\n| --- | --- | --- |\n${rows.join('\n')}\n`,
);
process.stdout.write(
  `ported=${counts.ported} not-applicable=${counts['not-applicable']} deferred=${counts.deferred} unclassified=${counts.missing}\n`,
);
